import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { latestManagerArtifact, managerArtifactAt } from './deployment-artifacts.mjs';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const deploysDirectory = resolve(repositoryRoot, 'deploys');
const outputPath = resolve(
  repositoryRoot,
  'apps/web/src/config/deployments.generated.ts'
);

// MANAGER_DEPLOYMENT_FILE pins one artifact (the walkthrough build, apps/e2e/scripts/build-app.mjs,
// points it at the e2e Manager); otherwise the newest real deployment wins.
const pinned = process.env.MANAGER_DEPLOYMENT_FILE?.trim();
const latest = pinned
  ? managerArtifactAt(resolve(repositoryRoot, pinned))
  : latestManagerArtifact(deploysDirectory);

const deploymentId = `manager:${latest.artifact.manager}`;
const output = `// Generated by scripts/generate-web-deployment.mjs. Do not edit.\n\nexport const DEPLOYMENT_ID = ${JSON.stringify(deploymentId)};\n`;

writeFileSync(outputPath, output);
console.log(`Web deployment set to ${deploymentId} (${latest.fileName})`);
