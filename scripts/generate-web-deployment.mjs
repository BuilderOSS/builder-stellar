import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { latestManagerArtifact } from './deployment-artifacts.mjs';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const deploysDirectory = resolve(repositoryRoot, 'deploys');
const outputPath = resolve(
  repositoryRoot,
  'apps/web/src/config/deployments.generated.ts'
);

const latest = latestManagerArtifact(deploysDirectory);

const deploymentId = `manager:${latest.artifact.manager}`;
const output = `// Generated by scripts/generate-web-deployment.mjs. Do not edit.\n\nexport const DEPLOYMENT_ID = ${JSON.stringify(deploymentId)};\n`;

writeFileSync(outputPath, output);
console.log(`Web deployment set to ${deploymentId} (${latest.fileName})`);
