import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const deploysDirectory = resolve(repositoryRoot, 'deploys');
const outputPath = resolve(
  repositoryRoot,
  'apps/web/src/config/deployments.generated.ts'
);

const artifacts = readdirSync(deploysDirectory)
  .filter((fileName) => fileName.endsWith('-manager.json'))
  .map((fileName) => {
    const path = resolve(deploysDirectory, fileName);
    const artifact = JSON.parse(readFileSync(path, 'utf8'));

    if (!artifact.manager || !artifact.deployedAt) {
      throw new Error(
        `Manager deployment artifact ${path} must define manager and deployedAt`
      );
    }

    return { artifact, fileName };
  })
  .sort(
    ({ artifact: left }, { artifact: right }) =>
      new Date(right.deployedAt).getTime() - new Date(left.deployedAt).getTime()
  );

const latest = artifacts[0];
if (!latest) {
  throw new Error(`No manager deployment artifacts found in ${deploysDirectory}`);
}

const deploymentId = `manager:${latest.artifact.manager}`;
const output = `// Generated by scripts/generate-web-deployment.mjs. Do not edit.\n\nexport const DEPLOYMENT_ID = ${JSON.stringify(deploymentId)};\n`;

writeFileSync(outputPath, output);
console.log(`Web deployment set to ${deploymentId} (${latest.fileName})`);
