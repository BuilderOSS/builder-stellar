#!/usr/bin/env bash
# Line, region and function coverage of the contract crates, for the audit package
# (docs/COVERAGE.md).
#
#   scripts/coverage.sh [output-dir]      (default coverage/contracts; pnpm contracts:coverage)
#
# Writes summary.txt and summary.json (per file and in total), lcov.info, an HTML report in html/,
# and README.txt naming the commit and toolchain. Needs cargo-llvm-cov
# (cargo install cargo-llvm-cov --locked) and the Stellar CLI the contracts build with.
set -euo pipefail

cd "$(dirname "$0")/.."
out="${1:-coverage/contracts}"

if ! command -v cargo-llvm-cov >/dev/null 2>&1; then
  echo "cargo-llvm-cov is not installed. Install it with: cargo install cargo-llvm-cov --locked" >&2
  exit 1
fi
# llvm-cov needs the LLVM tools of the pinned compiler (rust-toolchain.toml).
rustup component add llvm-tools-preview >/dev/null

# The e2e tests load the built WASM, so build it first. Code that runs inside the Soroban VM is not
# instrumented: the numbers count each crate's native test runs, the way `cargo test` runs them.
env -u SOROBAN_SDK_BUILD_SYSTEM_SUPPORTS_SPEC_SHAKING_V2 stellar contract build --locked >&2

# The same setting CI uses for the plain cargo steps.
export SOROBAN_SDK_BUILD_SYSTEM_SUPPORTS_SPEC_SHAKING_V2=0

# Report on contract source only: not the e2e harness, the test-only mock adapter, or test modules.
# Dependencies, OpenZeppelin included, are outside the workspace and never in the report.
ignore='contracts/(e2e|vote-adapter-mock)/|/src/test(s)?(\.rs|/)|/src/[a-z_]*_test\.rs$|/src/testutils?\.rs$'

cargo llvm-cov clean --workspace
cargo llvm-cov --locked --workspace --no-report
mkdir -p "$out"
rm -rf "$out/html"
cargo llvm-cov report --ignore-filename-regex "$ignore" --summary-only | tee "$out/summary.txt"
cargo llvm-cov report --ignore-filename-regex "$ignore" --json --summary-only --output-path "$out/summary.json"
cargo llvm-cov report --ignore-filename-regex "$ignore" --lcov --output-path "$out/lcov.info"
cargo llvm-cov report --ignore-filename-regex "$ignore" --html --output-dir "$out"

{
  echo "Contract coverage, generated by scripts/coverage.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "Commit: $(git rev-parse HEAD)$(git diff --quiet HEAD -- contracts Cargo.lock || echo ' (with uncommitted contract changes)')"
  echo "Toolchain: $(rustc --version); $(stellar --version | head -1); $(cargo llvm-cov --version)"
  echo "Excluded from the report: files matching ${ignore}"
} > "$out/README.txt"
echo "Coverage report: $out (open $out/html/index.html)" >&2
